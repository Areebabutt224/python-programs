#Checking Data Types
name = "Ali"
age = 25
height = 5.9
is_active = True

print(type(name))
print(type(age))
print(type(height))
print(type(is_active))

#String Data Type
city = "Rawalpindi"
print(city)
print(type(city))

#Integer Data Type
score = 100
print(score)
print(type(score))

#Float Data Type
price = 99.99
print(price)
print(type(price))

#List Data Type
fruits = ["Apple", "Banana", "Mango"]
print(fruits)
print(type(fruits))

#Dictionary Data Type
student = {"name": "Sara", "age": 21, "city": "Lahore"}
print(student)
print(type(student))

#Set Data Type
numbers = {1, 2, 3, 4, 5}
print(numbers)
print(type(numbers))